const GALLERY_SIZE = 5;

const FEATURES_PER_LISTING = 6;

const CLOSING_LINE =
    "Shown by private appointment only; full dossier and floor plans are released on request.";

function buildListing(seed: ListingSeed): Listing {
    const { blurb, imageSeed, featureOffset, ...rest } = seed;
    return {
        ...rest,
        agent: AGENTS[seed.agentId],
        images: propertyGallery(imageSeed, GALLERY_SIZE),
        description: `${blurb} ${CLOSING_LINE}`,
        features: Array.from(
            { length: FEATURES_PER_LISTING },
            (_, offset) =>
                FEATURE_POOL[(featureOffset + offset) % FEATURE_POOL.length],
        ),
        pricePerSqft: Math.round(seed.price / seed.sqft),
    };
}

export const LISTINGS: Listing[] = SEEDS.map(buildListing);

export const AVAILABLE_LISTINGS = LISTINGS.filter(
    (listing) => listing.status !== "SOLD",
);

export const RECENT_SALES = LISTINGS.filter(
    (listing) => listing.status === "SOLD",
).sort((a, b) => (a.soldMonthsAgo ?? 0) - (b.soldMonthsAgo ?? 0));

export const FEATURED_LISTINGS = AVAILABLE_LISTINGS.slice(0, 6);

export function getListing(id: string): Listing | undefined {
    return LISTINGS.find((listing) => listing.id === id);
}

export function getComparables(listing: Listing, limit = 4): Listing[] {
    const sameArea = LISTINGS.filter(
        (other) =>
            other.id !== listing.id && other.locality === listing.locality,
    );
    const elsewhere = LISTINGS.filter(
        (other) =>
            other.id !== listing.id && other.locality !== listing.locality,
    ).sort(
        (a, b) =>
            Math.abs(a.price - listing.price) -
            Math.abs(b.price - listing.price),
    );
    return [...sameArea, ...elsewhere].slice(0, limit);
}
